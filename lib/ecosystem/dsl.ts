export const tool = (
  id: string,
  route: string,
  title: string,
  summary: string,
  m: ModuleId,
  status: FrontendStatus,
  fields: Field[],
  sample: { title: string; items: string[] },
  parent?: string,
  runLabel = "Preview sample result",
) =>
  page(
    id,
    route,
    title,
    summary,
    m,
    status,
    [
      {
        kind: "notice",
        tone: "warning",
        body: "Demo preview. The result is a fixed, hand-written sample. It is not generated by AI and does not use what you enter. Nothing is analysed, saved or sent.",
      },
      { kind: "tool", fields, runLabel, sample },
    ],
    { parent },
  );

/** Generic preparation workspace: steps + draft input + tips. */
export const work = (
  id: string,
  route: string,
  title: string,
  summary: string,
  m: ModuleId,
  parent: string,
  steps: [string, string][],
  inputLabel: string,
  tips: string[],
) =>
  page(
    id,
    route,
    title,
    summary,
    m,
    FC,
    [
      {
        kind: "steps",
        title: "How to use this workspace",
        items: steps.map(([t, b]) => ({ title: t, body: b })),
      },
      {
        kind: "form",
        title: "Your notes",
        fields: [
          F.area("draft", inputLabel, false, {
            placeholder: "Write or paste here…",
          }),
        ],
        submit: "Save notes",
        note: "Saving is not connected yet.",
      },
      {
        kind: "list",
        title: "Tips",
        items: tips.map((t) => ({ title: t })),
      },
    ],
    { parent },
  );

