import type { Block, CollectionId, Field, FrontendStatus, ModuleId, PageDef } from "./types";

/** Authoring helpers for page definitions. Pure. */
export const EX: FrontendStatus = "existing";
export const FC: FrontendStatus = "frontend_complete";
export const FP: FrontendStatus = "frontend_partial";
export const RI: FrontendStatus = "requires_integration";
export const CS: FrontendStatus = "coming_soon";

export const F = {
  text: (name: string, label: string, required = false, extra: Partial<Field> = {}): Field => ({ name, label, type: "text", required, ...extra }),
  email: (name: string, label: string, required = false): Field => ({ name, label, type: "email", required }),
  area: (name: string, label: string, required = false, extra: Partial<Field> = {}): Field => ({ name, label, type: "textarea", required, ...extra }),
  sel: (name: string, label: string, options: string[], required = false): Field => ({ name, label, type: "select", options, required }),
  date: (name: string, label: string, required = false): Field => ({ name, label, type: "date", required }),
  file: (name: string, label: string, hint?: string): Field => ({ name, label, type: "file", hint }),
  check: (name: string, label: string): Field => ({ name, label, type: "checkbox" }),
  num: (name: string, label: string, required = false): Field => ({ name, label, type: "number", required }),
  url: (name: string, label: string, required = false): Field => ({ name, label, type: "url", required }),
};

export function page(
  id: string,
  route: string,
  title: string,
  summary: string,
  module: ModuleId,
  status: FrontendStatus,
  blocks: Block[],
  extra: Partial<PageDef> = {},
): PageDef {
  return { id, route, title, summary, module, status, blocks, ...extra };
}

export const hub = (
  id: string,
  route: string,
  title: string,
  summary: string,
  m: ModuleId,
  status: FrontendStatus,
  parent?: string,
  pre: Block[] = [],
  extra: Partial<PageDef> = {},
) =>
  page(
    id,
    route,
    title,
    summary,
    m,
    status,
    [...pre, { kind: "children" }],
    { parent, ...extra },
  );

